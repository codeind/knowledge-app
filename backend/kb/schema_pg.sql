-- Postgres version of schema.sql (used when DATABASE_URL is set). Keep the two in sync.

CREATE TABLE IF NOT EXISTS sources (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url         TEXT NOT NULL UNIQUE,
    title       TEXT NOT NULL,
    publisher   TEXT,
    kind        TEXT NOT NULL,          -- wiki | book | news | law | data | other
    licence     TEXT NOT NULL,          -- e.g. "CC BY-SA 4.0", "Public domain", "Link only"
    fetched_at  TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS passages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id   INTEGER NOT NULL REFERENCES sources(id) ON DELETE CASCADE,
    idx         INTEGER NOT NULL,       -- order within the source
    text        TEXT NOT NULL,
    UNIQUE (source_id, idx)
);

CREATE TABLE IF NOT EXISTS stories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS cards (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section       TEXT NOT NULL,        -- news | learn
    domain        TEXT NOT NULL,        -- history | ancient_history | economics | sports | laws_us | laws_in | science | world
    card_type     TEXT NOT NULL,        -- news | concept | event | profile | law | lesson | viewpoint | book
    title         TEXT NOT NULL,
    body          TEXT NOT NULL,
    label         TEXT NOT NULL DEFAULT 'Fact',          -- Fact | Interpretation | Opinion | Disputed
    viewpoint     TEXT,                 -- for viewpoint cards: the side it presents
    verification  TEXT NOT NULL DEFAULT 'unverified',    -- verified | single_source | unverified
    status        TEXT NOT NULL DEFAULT 'published',     -- published | rejected | draft
    quality_score REAL,                 -- share of claims the verifier marked supported (0..1)
    event_date    TEXT,                 -- ISO date the card is about (news date, event date)
    story_id      INTEGER REFERENCES stories(id),
    track_order   INTEGER,              -- ordering inside a Learn track
    origin        TEXT NOT NULL DEFAULT 'pipeline',      -- pipeline | seed
    created_at    TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')),
    UNIQUE (section, domain, title)
);

CREATE TABLE IF NOT EXISTS card_sources (
    card_id     INTEGER NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    source_id   INTEGER NOT NULL REFERENCES sources(id) ON DELETE CASCADE,
    PRIMARY KEY (card_id, source_id)
);

CREATE TABLE IF NOT EXISTS card_claims (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id     INTEGER NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    claim       TEXT NOT NULL,
    passage_ids TEXT NOT NULL DEFAULT '[]',   -- JSON list of passage ids
    verdict     TEXT NOT NULL DEFAULT 'unchecked'  -- supported | partial | unsupported | unchecked
);

CREATE TABLE IF NOT EXISTS entities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    kind        TEXT NOT NULL DEFAULT 'other'   -- organisation | person | place | object | law | event | other
);

CREATE TABLE IF NOT EXISTS card_entities (
    card_id     INTEGER NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    entity_id   INTEGER NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    PRIMARY KEY (card_id, entity_id)
);

CREATE TABLE IF NOT EXISTS card_tags (
    card_id     INTEGER NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    tag         TEXT NOT NULL,
    PRIMARY KEY (card_id, tag)
);

CREATE TABLE IF NOT EXISTS card_links (
    from_id     INTEGER NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    to_id       INTEGER NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    relation    TEXT NOT NULL,          -- related | explainer | player | viewpoint
    score       REAL,
    manual      INTEGER NOT NULL DEFAULT 0,   -- 1 = set by hand (seed/editor), kept when links are rebuilt
    PRIMARY KEY (from_id, to_id, relation)
);

CREATE TABLE IF NOT EXISTS books (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          TEXT NOT NULL,
    author         TEXT,
    year           INTEGER,
    url            TEXT NOT NULL UNIQUE,
    public_domain  INTEGER NOT NULL,    -- 1 = text may be quoted/summarised; 0 = title link only
    subjects       TEXT NOT NULL DEFAULT ''   -- comma-separated tags
);

CREATE TABLE IF NOT EXISTS card_books (
    card_id     INTEGER NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    book_id     INTEGER NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    PRIMARY KEY (card_id, book_id)
);

CREATE TABLE IF NOT EXISTS saves (
    user_id     TEXT NOT NULL DEFAULT 'local',
    card_id     INTEGER NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
    saved_at    TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')),
    PRIMARY KEY (user_id, card_id)
);

CREATE TABLE IF NOT EXISTS pipeline_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job           TEXT NOT NULL,
    started_at    TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')),
    finished_at   TEXT,
    cards_drafted INTEGER NOT NULL DEFAULT 0,
    cards_published INTEGER NOT NULL DEFAULT 0,
    cards_rejected  INTEGER NOT NULL DEFAULT 0,
    notes         TEXT
);

CREATE INDEX IF NOT EXISTS idx_cards_section ON cards(section, domain, status);
CREATE INDEX IF NOT EXISTS idx_cards_story ON cards(story_id);
CREATE INDEX IF NOT EXISTS idx_card_tags_tag ON card_tags(tag);

CREATE UNIQUE INDEX IF NOT EXISTS idx_entities_name_ci ON entities (LOWER(name));
